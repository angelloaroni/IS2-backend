BEGIN;

-- Infraestructura productora de A. Activación/consumidores corresponden a Fase 2.
CREATE TABLE IF NOT EXISTS public.evento_pendiente (
  id_evento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL,
  referencia VARCHAR(160) NOT NULL,
  payload JSONB NOT NULL CHECK (jsonb_typeof(payload) = 'object'),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (nombre, referencia)
);
CREATE TABLE IF NOT EXISTS public.entrega_evento (
  id_evento BIGINT NOT NULL REFERENCES public.evento_pendiente(id_evento),
  consumidor VARCHAR(80) NOT NULL,
  confirmado_en TIMESTAMPTZ,
  intentos INTEGER NOT NULL DEFAULT 0 CHECK (intentos >= 0),
  proximo_intento_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id_evento, consumidor)
);
CREATE INDEX IF NOT EXISTS entrega_evento_pendiente_idx
  ON public.entrega_evento (consumidor, proximo_intento_en, id_evento)
  WHERE confirmado_en IS NULL;

COMMIT;
