-- Configuración, referencias idempotentes y entregas recuperables de B.
BEGIN;

CREATE TABLE IF NOT EXISTS public.configuracion_ranking
(
  id_config SMALLINT PRIMARY KEY CHECK (id_config = 1),
  desde DATE,
  hasta DATE,
  CONSTRAINT configuracion_ranking_periodo_valido
    CHECK (desde IS NULL OR hasta IS NULL OR desde < hasta)
);

INSERT INTO public.configuracion_ranking (id_config, desde, hasta)
VALUES (1, NULL, NULL)
ON CONFLICT (id_config) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.usuario_excluido_ranking
(
  id_user INT PRIMARY KEY REFERENCES public.usuario(id_user)
);

ALTER TABLE public.notificacion
  ADD COLUMN IF NOT EXISTS referencia_evento VARCHAR(160);

CREATE UNIQUE INDEX IF NOT EXISTS notificacion_referencia_evento_unique
  ON public.notificacion (referencia_evento)
  WHERE referencia_evento IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.evento_pendiente
(
  id_evento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  referencia_evento VARCHAR(160) NOT NULL UNIQUE,
  tipo VARCHAR(64) NOT NULL,
  payload JSONB NOT NULL,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.entrega_evento
(
  id_evento BIGINT NOT NULL REFERENCES public.evento_pendiente(id_evento),
  consumidor VARCHAR(32) NOT NULL,
  entregado_en TIMESTAMPTZ,
  intentos INT NOT NULL DEFAULT 0 CHECK (intentos >= 0),
  ultimo_error VARCHAR(1000),
  proximo_intento_en TIMESTAMPTZ,
  PRIMARY KEY (id_evento, consumidor)
);

CREATE INDEX IF NOT EXISTS entrega_evento_pendiente_idx
  ON public.entrega_evento (proximo_intento_en, id_evento)
  WHERE entregado_en IS NULL;

CREATE TABLE IF NOT EXISTS public.ranking_top10_estado
(
  periodo VARCHAR(7) NOT NULL,
  id_user INT NOT NULL REFERENCES public.usuario(id_user),
  PRIMARY KEY (periodo, id_user)
);

COMMIT;
