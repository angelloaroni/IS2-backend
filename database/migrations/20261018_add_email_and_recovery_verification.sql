BEGIN;

ALTER TABLE public.usuario
  ADD COLUMN IF NOT EXISTS correo_institucional VARCHAR(254);

CREATE UNIQUE INDEX IF NOT EXISTS usuario_correo_institucional_unique
  ON public.usuario (correo_institucional)
  WHERE correo_institucional IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.verificacion_correo
(
  id_verificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  correo_institucional VARCHAR(254) NOT NULL,
  proposito VARCHAR(16) NOT NULL
    CHECK (proposito IN ('registro', 'recuperacion')),
  codigo_hash CHAR(64) NOT NULL,
  id_user INT REFERENCES public.usuario(id_user),
  expira_en TIMESTAMPTZ NOT NULL,
  intentos SMALLINT NOT NULL DEFAULT 0
    CHECK (intentos >= 0),
  verificado_en TIMESTAMPTZ,
  token_hash CHAR(64),
  token_expira_en TIMESTAMPTZ,
  utilizado_en TIMESTAMPTZ,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS verificacion_correo_busqueda_idx
  ON public.verificacion_correo (correo_institucional, proposito, creado_en DESC);

CREATE UNIQUE INDEX IF NOT EXISTS verificacion_correo_token_hash_unique
  ON public.verificacion_correo (token_hash)
  WHERE token_hash IS NOT NULL;

COMMIT;
