BEGIN;

CREATE TABLE IF NOT EXISTS public.usuario
(
  cod_user VARCHAR(8) NOT NULL,
  id_user INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR NOT NULL,
  puntos FLOAT NOT NULL,
  tipo VARCHAR NOT NULL,
  contrasena VARCHAR NOT NULL,
  estado BOOLEAN NOT NULL,
  CONSTRAINT usuario_cod_user_unique UNIQUE (cod_user),
  CONSTRAINT usuario_cod_user_formato CHECK (cod_user ~ '^[0-9]{8}$')
);

CREATE TABLE IF NOT EXISTS public.tachointeligente
(
  id_tacho INT PRIMARY KEY,
  latitud FLOAT NOT NULL,
  longitud FLOAT NOT NULL,
  capacidad BOOLEAN NOT NULL,
  estado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS public.residuo
(
  id_residuo INT PRIMARY KEY,
  peso FLOAT NOT NULL,
  tipo VARCHAR(32) NOT NULL,
  idempotency_key VARCHAR(128),
  id_user INT NOT NULL REFERENCES public.usuario(id_user),
  id_tacho INT NOT NULL REFERENCES public.tachointeligente(id_tacho)
);

CREATE TABLE IF NOT EXISTS public.logros
(
  id_logro INT PRIMARY KEY,
  nombre VARCHAR NOT NULL,
  tipo_condicion VARCHAR NOT NULL,
  valor_objetivo FLOAT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.logros_usuario
(
  fecha_obtencion DATE NOT NULL,
  id_logro INT NOT NULL REFERENCES public.logros(id_logro),
  id_user INT NOT NULL REFERENCES public.usuario(id_user),
  PRIMARY KEY (id_logro, id_user)
);

CREATE TABLE IF NOT EXISTS public.premio
(
  id_premio INT PRIMARY KEY,
  nombre VARCHAR NOT NULL,
  descripcion VARCHAR NOT NULL,
  costo FLOAT NOT NULL,
  stock INT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.usuario_premio
(
  id_usuario_premio INT PRIMARY KEY,
  fecha_obtencion DATE NOT NULL,
  id_premio INT NOT NULL REFERENCES public.premio(id_premio),
  id_user INT NOT NULL REFERENCES public.usuario(id_user)
);

CREATE TABLE IF NOT EXISTS public.notificacion
(
  id_notificacion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_user INT NOT NULL REFERENCES public.usuario(id_user),
  tipo VARCHAR NOT NULL,
  titulo VARCHAR NOT NULL,
  mensaje VARCHAR NOT NULL,
  fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  leida BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS public.historialreciclaje
(
  id_historial INT PRIMARY KEY,
  fecha DATE NOT NULL,
  id_user INT NOT NULL REFERENCES public.usuario(id_user),
  id_tacho INT NOT NULL REFERENCES public.tachointeligente(id_tacho),
  id_residuo INT NOT NULL REFERENCES public.residuo(id_residuo)
);

ALTER TABLE public.tachointeligente
  ADD COLUMN IF NOT EXISTS estado BOOLEAN NOT NULL DEFAULT TRUE;

ALTER TABLE public.residuo
  ADD COLUMN IF NOT EXISTS idempotency_key VARCHAR(128);

CREATE UNIQUE INDEX IF NOT EXISTS residuo_idempotency_key_unique
  ON public.residuo (idempotency_key);

COMMIT;
