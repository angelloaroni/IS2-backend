CREATE TABLE Usuario
(
  cod_user VARCHAR(8) NOT NULL,
  id_user INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  nombre VARCHAR NOT NULL,
  puntos FLOAT NOT NULL,
  tipo VARCHAR NOT NULL,
  contrasena VARCHAR NOT NULL,
  estado BOOL NOT NULL,
  PRIMARY KEY (id_user),
  CONSTRAINT usuario_cod_user_unique UNIQUE (cod_user),
  CONSTRAINT usuario_cod_user_formato CHECK (cod_user ~ '^[0-9]{8}$')
);

CREATE TABLE TachoInteligente
(
  id_tacho INT NOT NULL,
  latitud FLOAT NOT NULL,
  longitud FLOAT NOT NULL,
  capacidad BOOL NOT NULL,
  PRIMARY KEY (id_tacho)
);

CREATE TABLE Residuo
(
  id_residuo INT NOT NULL,
  peso FLOAT NOT NULL,
  tipo VARCHAR NOT NULL,
  id_user INT NOT NULL,
  id_tacho INT NOT NULL,
  PRIMARY KEY (id_residuo),
  FOREIGN KEY (id_user) REFERENCES Usuario(id_user),
  FOREIGN KEY (id_tacho) REFERENCES TachoInteligente(id_tacho)
);

CREATE TABLE Logros
(
  id_logro INT NOT NULL,
  nombre VARCHAR NOT NULL,
  tipo_condicion VARCHAR NOT NULL,
  valor_objetivo FLOAT NOT NULL,
  PRIMARY KEY (id_logro)
);

CREATE TABLE Logros_Usuario
(
  fecha_obtencion DATE NOT NULL,
  id_logro INT NOT NULL,
  id_user INT NOT NULL,
  PRIMARY KEY (id_logro, id_user),
  FOREIGN KEY (id_logro) REFERENCES Logros(id_logro),
  FOREIGN KEY (id_user) REFERENCES Usuario(id_user)
);

CREATE TABLE Premio
(
  id_premio INT NOT NULL,
  nombre VARCHAR NOT NULL,
  descripcion VARCHAR NOT NULL,
  costo FLOAT NOT NULL,
  stock INT NOT NULL,
  PRIMARY KEY (id_premio)
);

CREATE TABLE usuario_Premio
(
  id_usuario_premio INT NOT NULL,
  fecha_obtencion DATE NOT NULL,
  id_premio INT NOT NULL,
  id_user INT NOT NULL,
  PRIMARY KEY (id_usuario_premio),
  FOREIGN KEY (id_premio) REFERENCES Premio(id_premio),
  FOREIGN KEY (id_user) REFERENCES Usuario(id_user)
);

CREATE TABLE Notificacion
(
  id_notificacion INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_user INT NOT NULL,
  tipo VARCHAR NOT NULL,
  titulo VARCHAR NOT NULL,
  mensaje VARCHAR NOT NULL,
  fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  leida BOOL NOT NULL DEFAULT FALSE,
  PRIMARY KEY (id_notificacion),
  FOREIGN KEY (id_user) REFERENCES Usuario(id_user)
);

CREATE TABLE HistorialReciclaje
(
  id_historial INT NOT NULL,
  fecha DATE NOT NULL,
  id_user INT NOT NULL,
  id_tacho INT NOT NULL,
  id_residuo INT NOT NULL,
  PRIMARY KEY (id_historial),
  FOREIGN KEY (id_user) REFERENCES Usuario(id_user),
  FOREIGN KEY (id_tacho) REFERENCES TachoInteligente(id_tacho),
  FOREIGN KEY (id_residuo) REFERENCES Residuo(id_residuo)
);
